/**
 * Unit tests for the soft band of road mode (review 2026-10-16): reading
 * public/road-lines/<slug>.json (web/src/data/road-line.ts) and what the map draws from it
 * (web/src/map/road-outline.ts).
 */
import assert from 'node:assert/strict';
import { describe, it } from 'node:test';
import { existsSync, readFileSync } from 'node:fs';
import { roadLine, roadOutline } from './helpers/src.mjs';

const { parseRoadLineFile, roadLineUrl } = roadLine;
const { roadOutlineCollection, roadOutlineLayer, ROAD_OUTLINE_LAYER, SRC_ROAD_OUTLINE } = roadOutline;

describe('road-lines files', () => {
  it('only A- and N-roads have a file, by the slug of the normalised number', () => {
    assert.equal(roadLineUrl('A2'), '/road-lines/a2.json');
    assert.equal(roadLineUrl('a 27'), '/road-lines/a27.json');
    assert.equal(roadLineUrl('N210'), '/road-lines/n210.json');
    assert.equal(roadLineUrl('S100'), null);
    assert.equal(roadLineUrl('Croeselaan'), null);
  });

  it('keeps the valid lines and refuses what is no road-lines file', () => {
    const lines = parseRoadLineFile({ road: 'A2', lines: [[[5, 52], [5.1, 52.1]], [[5, 52]], 'x', [[5, 52], ['a', 1], [5.2, 52.2]]] });
    assert.deepEqual(lines, [[[5, 52], [5.1, 52.1]], [[5, 52], [5.2, 52.2]]]);
    assert.equal(parseRoadLineFile(null), null);
    assert.equal(parseRoadLineFile({ lines: 'no' }), null);
    assert.equal(parseRoadLineFile({ lines: [[[5, 52]]] }), null, 'a single point is no line');
  });

  it('the committed A2 file is a real course from Amsterdam to Maastricht', () => {
    const file = new URL('../public/road-lines/a2.json', import.meta.url);
    if (!existsSync(file)) return; // generated by pipeline/bin/build-road-lines.js
    const lines = parseRoadLineFile(JSON.parse(readFileSync(file, 'utf8')));
    assert.ok(lines && lines.length > 0);
    const lats = lines.flat().map((c) => c[1]);
    assert.ok(Math.max(...lats) > 52.3 && Math.min(...lats) < 50.9, 'reaches Amsterdam and Maastricht');
  });
});

describe('the band on the map', () => {
  it('one MultiLineString feature, or an empty collection', () => {
    assert.deepEqual(roadOutlineCollection(null).features, []);
    assert.deepEqual(roadOutlineCollection([]).features, []);
    const fc = roadOutlineCollection([[[5, 52], [5.1, 52.1]]]);
    assert.equal(fc.features.length, 1);
    assert.equal(fc.features[0].geometry.type, 'MultiLineString');
  });

  it('a soft line of its own source, never in a verdict colour', () => {
    for (const theme of ['light', 'dark']) {
      const layer = roadOutlineLayer(theme);
      assert.equal(layer.id, ROAD_OUTLINE_LAYER);
      assert.equal(layer.source, SRC_ROAD_OUTLINE);
      assert.equal(layer.type, 'line');
      assert.ok(layer.paint['line-opacity'] <= 0.35, 'faint');
    }
  });
});
